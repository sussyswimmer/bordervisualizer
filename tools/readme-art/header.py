"""Writes the README's animated header (assets/header.svg) and footer wave (assets/footer.svg).

Usage: python3 tools/readme-art/header.py <assets dir>

The header is assets/banner.svg (the glowing screen, the wordmark and the tagline, reused as is) under a band of
flowing waves, with the glow pulsing on a beat and the colors moving through the presets' palettes. Everything is
CSS animation inside the SVG, so GitHub shows it animated, and it holds still for viewers who ask for reduced motion.
"""
import math, os, re, sys

WIDTH = 1280
SHIFT = 70                      # the banner moves down this far, under the wave band
HEIGHT = 640 + SHIFT

# The rim colors cycle through these (doc 06 presets): brand, sunset, aurora, back to brand.
CYCLE = [('#7C5CFF', '#22D3EE'), ('#FF8A2A', '#FF4F9A'), ('#14E3C5', '#9D4DFF'), ('#7C5CFF', '#22D3EE')]
CYCLE_SECONDS = 18


def wave_path(base, amplitude, length, phase, top, width):
    """A filled band from y = top to a sine wave around y = base, `width` wide."""
    points = []
    for x in range(0, width + 1, 16):
        y = base + amplitude * math.sin(2 * math.pi * x / length + phase)
        points.append(f'{x},{y:.1f}')
    return f'M0,{top} L' + ' L'.join(points) + f' L{width},{top} Z'


def keyframes(name, prop, values):
    steps = len(values) - 1
    frames = ' '.join(f'{100 * i / steps:.1f}% {{ {prop}: {v}; }}' for i, v in enumerate(values))
    return f'@keyframes {name} {{ {frames} }}'


def waves(top_edge, flip, ids):
    """Three wave layers that slide left forever; seamless because each slides one full gradient period."""
    period = 2 * WIDTH                     # the gradient reflects, so it repeats every 2 x WIDTH
    layers = []
    for i, (base, amp, length, phase, opacity, seconds) in enumerate(
            [(54, 14, 640, 0.0, 0.35, 26), (46, 18, 853.33, 1.3, 0.55, 19), (36, 12, 1280, 2.4, 1.0, 13)]):
        d = wave_path(base, amp, length, phase, 0, WIDTH + period)
        transform = f'translate(0,{top_edge}) scale(1,-1)' if flip else ''
        layers.append(
            f'<g transform="{transform}"><path class="slide{i}" d="{d}" fill="url(#{ids})" opacity="{opacity}"/></g>')
    css = ' '.join(
        f'.slide{i} {{ animation: slide {s}s linear infinite; }}' for i, s in enumerate((26, 19, 13)))
    css += f' @keyframes slide {{ from {{ transform: translateX(0); }} to {{ transform: translateX(-{period}px); }} }}'
    return '\n  '.join(layers), css


def gradient(gid, x1, y1, x2, y2, extra=''):
    """A two-stop gradient whose colors move through CYCLE (SMIL: browsers repaint it, unlike CSS on <stop>)."""
    def stop(offset, colors):
        values = ';'.join(colors)
        return (f'<stop offset="{offset}" stop-color="{colors[0]}"><animate attributeName="stop-color" '
                f'values="{values}" dur="{CYCLE_SECONDS}s" repeatCount="indefinite" calcMode="spline" '
                f'keySplines="{"; ".join(["0.45 0 0.55 1"] * (len(colors) - 1))}"/></stop>')
    return (f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"{extra}>'
            f'{stop(0, [a for a, _ in CYCLE])}{stop(1, [b for _, b in CYCLE])}</linearGradient>')


def header(banner):
    body = banner[banner.index('<defs>'):banner.rindex('</svg>')]
    # The rim's two gradients follow the color cycle.
    body = re.sub(r'<linearGradient id="rim".*?</linearGradient>',
                  gradient('rim', 170, 100, 1110, 540), body, flags=re.S)
    # The glow beats: the light around and inside the screen swells on each beat (two beats a second, the downbeat
    # strongest), as the app's glow does. Each layer keeps its own opacity; the group's pulses over it.
    for layer in ('filter="url(#bloom)"', 'filter="url(#halo)"', 'filter="url(#spill-far)"', 'filter="url(#spill-near)"'):
        body = re.sub(r'(<rect [^>]*' + re.escape(layer) + r'/>)', r'<g class="beat">\1</g>', body)
    defs_end = body.index('</defs>')
    defs, content = body[:defs_end], body[defs_end + len('</defs>'):]
    wave_layers, wave_css = waves(0, False, 'wave')
    beat = ('@keyframes beat { 0% { opacity: 1; } 12% { opacity: 0.92; } 50% { opacity: 0.6; } '
            '54% { opacity: 0.86; } 100% { opacity: 0.6; } } '
            '.beat { animation: beat 1s ease-out infinite; }')
    style = f'@media (prefers-reduced-motion: no-preference) {{ {beat} {wave_css} }}'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-labelledby="title">
  <title id="title">Rimlight: your screen, lit by your music.</title>
  <!-- Generated by tools/readme-art/header.py from assets/banner.svg: edit those, not this file. -->
  <style>{style}</style>
  {defs}
    {gradient('wave', 0, 0, WIDTH, 0, ' spreadMethod="reflect"')}
    <clipPath id="card"><rect width="{WIDTH}" height="{HEIGHT}" rx="28"/></clipPath>
  </defs>
  <g clip-path="url(#card)">
  <rect width="{WIDTH}" height="{HEIGHT}" fill="#0A0A0F"/>
  {wave_layers}
  <g transform="translate(0,{SHIFT})">{content}</g>
  </g>
</svg>
'''


def footer():
    height = 90
    wave_layers, wave_css = waves(height, True, 'wave')
    style = f'@media (prefers-reduced-motion: no-preference) {{ {wave_css} }}'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" viewBox="0 0 {WIDTH} {height}" aria-hidden="true">
  <!-- Generated by tools/readme-art/header.py: edit that, not this file. -->
  <style>{style}</style>
  <defs>{gradient('wave', 0, 0, WIDTH, 0, ' spreadMethod="reflect"')}</defs>
  {wave_layers}
</svg>
'''


def main():
    out = sys.argv[1]
    banner = open(os.path.join(out, 'banner.svg'), encoding='utf-8').read()
    with open(os.path.join(out, 'header.svg'), 'w', encoding='utf-8') as f:
        f.write(header(banner))
    with open(os.path.join(out, 'footer.svg'), 'w', encoding='utf-8') as f:
        f.write(footer())


if __name__ == '__main__':
    main()
